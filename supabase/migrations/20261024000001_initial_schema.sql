-- NyaySutra AI — application schema for Supabase Postgres.
-- Mirrors the SQLite schema in nyaya/db.py (SCHEMA + MIGRATIONS + ADDED_COLUMNS, schema_version 1).
-- Differences, all deliberate:
--   * FTS5 virtual table  -> generated tsvector column chunks.fts + GIN index (same weighting idea: header > text)
--   * JSON columns        -> jsonb (queried with ->>, same operator the SQLite code uses)
--   * INTEGER PRIMARY KEY -> bigint identity "by default" (so existing ids can be copied unchanged)
--   * timestamps stay ISO-8601 text: the application compares and slices them as strings
--   * embeddings stay bytea float32 (identical bytes); search runs in the app's exact in-memory index
-- Idempotent: safe to re-run.

create table if not exists public.meta (
    key   text primary key,
    value text
);

create table if not exists public.cases (
    id                text primary key,
    title             text not null,
    case_type         text not null,
    case_number       text default '',
    court             text default '',
    client_name       text default '',
    client_role       text default '',
    opposite_party    text default '',
    filing_date       text,
    next_hearing_date text,
    status            text default 'Active / In Court',
    acts_sections     text default '',
    description       text default '',
    created_at        text not null,
    updated_at        text not null,
    opposite_role     text default '',
    filing_number     text default '',
    fir_number        text default '',
    cnr_number        text default '',
    state             text default '',
    district          text default '',
    police_station    text default '',
    filing_year       integer,
    case_subtype      text default '',
    is_draft          integer default 0
);
create index if not exists ix_cases_cnr on public.cases(cnr_number);
create index if not exists ix_cases_updated on public.cases(updated_at desc);
create index if not exists ix_cases_hearing on public.cases(next_hearing_date);

create table if not exists public.case_notes (
    id         text primary key,
    case_id    text not null references public.cases(id) on delete cascade,
    author     text default 'Advocate',
    content    text not null,
    created_at text not null
);
create index if not exists ix_case_notes_case on public.case_notes(case_id, created_at desc);

-- collection: case (a matter's own files) | bare_act | draft | judgment (shared library)
create table if not exists public.documents (
    id         text primary key,
    case_id    text references public.cases(id) on delete cascade,
    collection text not null check (collection in ('case', 'bare_act', 'draft', 'judgment')),
    doc_type   text not null,
    title      text not null,
    filename   text not null,
    path       text not null,          -- 'sb://<bucket>/<key>' (Supabase Storage) or a project-relative library path
    sha256     text not null,
    pages      integer default 0,
    chars      integer default 0,
    n_chunks   integer default 0,
    status     text not null default 'processing' check (status in ('processing', 'ready', 'failed')),
    error      text,
    meta       jsonb default '{}'::jsonb,
    created_at text not null
);
create unique index if not exists ux_documents_sha on public.documents(coalesce(case_id, ''), sha256);
create index if not exists ix_documents_case on public.documents(case_id);
create index if not exists ix_documents_collection on public.documents(collection);
create index if not exists ix_documents_derived on public.documents((meta->>'derived_from'));

create table if not exists public.chunks (
    id         bigint generated by default as identity primary key,
    doc_id     text not null references public.documents(id) on delete cascade,
    ord        integer not null,
    header     text not null,
    text       text not null,
    page_start integer,
    page_end   integer,
    label      text,                    -- e.g. 'Section 73', 'Article 21', 'Order XXXIX Rule 1', 'paras 12-15'
    section    text,                    -- normalised number for exact lookup, e.g. '73', '138A', 'XXXIX.1'
    title      text,
    chapter    text,
    emb        bytea,                   -- float32 embedding (searched in the app's exact in-memory index)
    fts        tsvector generated always as (
                   setweight(to_tsvector('english', coalesce(header, '')), 'A') ||
                   setweight(to_tsvector('english', coalesce(text, '')), 'B')) stored
);
create index if not exists ix_chunks_doc on public.chunks(doc_id, ord);
create index if not exists ix_chunks_section on public.chunks(section);
create index if not exists ix_chunks_fts on public.chunks using gin(fts);

create table if not exists public.chats (
    id         text primary key,
    case_id    text references public.cases(id) on delete cascade,
    title      text not null,
    created_at text not null,
    updated_at text not null
);
create index if not exists ix_chats_case on public.chats(case_id, updated_at);

create table if not exists public.messages (
    id         bigint generated by default as identity primary key,
    chat_id    text not null references public.chats(id) on delete cascade,
    role       text not null,
    content    text not null,
    sources    jsonb default '[]'::jsonb,
    meta       jsonb default '{}'::jsonb,
    created_at text not null
);
create index if not exists ix_messages_chat on public.messages(chat_id, id);

create table if not exists public.prefs (
    key        text primary key,
    value      text not null,
    updated_at text not null
);

create table if not exists public.audit_log (
    id        bigint generated by default as identity primary key,
    at        text not null,
    action    text not null,
    entity    text not null,
    entity_id text,
    detail    jsonb default '{}'::jsonb
);
create index if not exists ix_audit_at on public.audit_log(at);

create table if not exists public.notifications (
    id         bigint generated by default as identity primary key,
    kind       text not null,
    title      text not null,
    body       text default '',
    link       text default '',
    case_id    text references public.cases(id) on delete cascade,
    dedupe_key text unique,
    created_at text not null,
    read_at    text
);
create index if not exists ix_notifications_created on public.notifications(created_at);
create index if not exists ix_notifications_unread on public.notifications(created_at) where read_at is null;

create table if not exists public.integrations (
    id              text primary key,
    enabled         integer not null default 1,
    status          text not null default 'never',
    last_attempt_at text,
    last_success_at text,
    last_error      text,
    fail_count      integer not null default 0,
    next_due_at     text,
    etag            text,
    last_modified   text
);

create table if not exists public.sync_log (
    id             bigint generated by default as identity primary key,
    integration_id text not null,
    trigger        text not null,
    started_at     text not null,
    finished_at    text,
    outcome        text,
    items_new      integer default 0,
    items_updated  integer default 0,
    error          text
);
create index if not exists ix_sync_log on public.sync_log(integration_id, started_at);

create table if not exists public.source_records (
    id           text primary key,
    source       text not null,
    external_id  text not null,
    kind         text not null,
    title        text not null,
    url          text default '',
    jurisdiction text default '',
    published_at text,
    retrieved_at text not null,
    verified_at  text,
    content_hash text not null,
    provenance   text not null,
    data         jsonb default '{}'::jsonb,
    case_id      text references public.cases(id) on delete set null,
    unique (source, external_id)
);
create index if not exists ix_source_records_case on public.source_records(case_id);
create index if not exists ix_source_records_kind on public.source_records(kind, published_at);

create table if not exists public.doc_derivatives (
    doc_id     text not null references public.documents(id) on delete cascade,
    kind       text not null,
    lang       text default 'en',
    content    text not null,
    meta       jsonb default '{}'::jsonb,
    created_at text not null,
    primary key (doc_id, kind)
);

create table if not exists public.drafts (
    id         text primary key,
    case_id    text references public.cases(id) on delete cascade,
    kind       text not null default 'draft' check (kind in ('draft', 'notice')),
    doc_type   text not null,
    forum      text default '',
    style      text default 'formal',
    lang       text default 'en',
    title      text not null,
    content    text not null,
    facts      jsonb default '[]'::jsonb,
    missing    jsonb default '[]'::jsonb,
    sources    jsonb default '[]'::jsonb,
    inputs     jsonb default '{}'::jsonb,
    version    integer not null default 1,
    created_at text not null,
    updated_at text not null
);
create index if not exists ix_drafts_case on public.drafts(case_id, updated_at);

create table if not exists public.draft_versions (
    draft_id   text not null references public.drafts(id) on delete cascade,
    version    integer not null,
    content    text not null,
    note       text default '',
    created_at text not null,
    primary key (draft_id, version)
);

create table if not exists public.case_provisions (
    id           text primary key,
    case_id      text not null references public.cases(id) on delete cascade,
    act          text not null,
    ref          text not null,
    title        text default '',
    chunk_id     bigint,
    doc_id       text,
    page         integer,
    reason       text default '',
    flags        jsonb default '[]'::jsonb,
    verification text not null,
    status       text not null default 'suggested' check (status in ('suggested', 'accepted', 'rejected', 'edited')),
    note         text default '',
    created_at   text not null,
    updated_at   text not null,
    unique (case_id, act, ref)
);

-- The application checks this to refuse running against an un-migrated database.
insert into public.meta(key, value) values ('schema_version', '1')
on conflict (key) do update set value = excluded.value;
